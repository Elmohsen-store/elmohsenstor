-- اجعل نوع product_id مطابقاً تماماً لنوع products.id (سواء كان bigint أو uuid).
do $$
declare
  product_type text;
  child_table text;
  child_type text;
  has_rows boolean;
begin
  select format_type(a.atttypid, a.atttypmod)
    into product_type
  from pg_attribute a
  where a.attrelid = 'public.products'::regclass
    and a.attname = 'id' and not a.attisdropped;

  if product_type not in ('bigint','uuid') then
    raise exception 'نوع products.id غير مدعوم: %. يجب أن يكون bigint أو uuid', product_type;
  end if;

  foreach child_table in array array['order_items','cart_items','wishlist','reviews'] loop
    if to_regclass('public.' || child_table) is not null then
      select format_type(a.atttypid,a.atttypmod)
        into child_type
      from pg_attribute a
      where a.attrelid = to_regclass('public.' || child_table)
        and a.attname = 'product_id' and not a.attisdropped;

      if child_type is not null and child_type <> product_type then
        execute format('select exists(select 1 from public.%I limit 1)', child_table) into has_rows;
        if has_rows then
          raise exception 'الجدول public.% يحتوي بيانات وproduct_id نوعه % بينما products.id نوعه %. يلزم ترحيل القيم القديمة وربطها قبل إعادة تشغيل قاعدة البيانات.', child_table, child_type, product_type;
        end if;
        execute format('alter table public.%I alter column product_id type %s using product_id::text::%s',
                       child_table, product_type, product_type);
      end if;
    end if;
  end loop;
end $$;

