-- تحديث مهم: البائع الجديد يبقى Buyer حتى موافقة المدير، مع إنشاء طلب بائع تلقائيًا.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public as $$
declare wanted_type text;
begin
  wanted_type:=coalesce(new.raw_user_meta_data->>'account_type','buyer');
  if wanted_type not in ('buyer','seller') then wanted_type:='buyer'; end if;
  insert into public.profiles(id,full_name,phone,account_type,store_name,address)
  values(new.id,nullif(new.raw_user_meta_data->>'full_name',''),nullif(new.raw_user_meta_data->>'phone',''),case when wanted_type='seller' then 'buyer' else wanted_type end,nullif(new.raw_user_meta_data->>'store_name',''),nullif(new.raw_user_meta_data->>'address',''))
  on conflict(id) do update set full_name=excluded.full_name,phone=excluded.phone,store_name=excluded.store_name,address=excluded.address;
  if wanted_type='seller' then
    insert into public.seller_applications(user_id,full_name,email,phone,store_name,address)
    values(new.id,coalesce(nullif(new.raw_user_meta_data->>'full_name',''),'غير محدد'),new.email,coalesce(nullif(new.raw_user_meta_data->>'phone',''),'غير محدد'),nullif(new.raw_user_meta_data->>'store_name',''),nullif(new.raw_user_meta_data->>'address',''));
  end if;
  return new;
end; $$;
