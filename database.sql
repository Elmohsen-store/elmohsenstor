-- Profiles
drop policy if exists "profiles_select_own_or_admin" on public.profiles;
create policy "profiles_select_own_or_admin"
on public.profiles for select
to authenticated
using (id = auth.uid() or public.is_admin());

drop policy if exists "profiles_update_own_or_admin" on public.profiles;
create policy "profiles_update_own_or_admin"
on public.profiles for update
to authenticated
using (id = auth.uid() or public.is_admin())
with check (id = auth.uid() or public.is_admin());

-- Products: الجميع يشاهد المنتجات النشطة
drop policy if exists "products_select_active" on public.products;
create policy "products_select_active"
on public.products for select
to anon, authenticated
using (is_active = true or public.is_admin() or seller_id = auth.uid());

-- المدير والبائع الموافق عليه يستطيعان إضافة منتجات
drop policy if exists "products_insert_admin_or_seller" on public.products;
create policy "products_insert_admin_or_seller"
on public.products for insert
to authenticated
with check (
  public.is_admin()
  or (public.is_seller() and seller_id = auth.uid())
);

drop policy if exists "products_update_admin_or_owner" on public.products;
create policy "products_update_admin_or_owner"
on public.products for update
to authenticated
using (public.is_admin() or seller_id = auth.uid())
with check (public.is_admin() or seller_id = auth.uid());

drop policy if exists "products_delete_admin_or_owner" on public.products;
create policy "products_delete_admin_or_owner"
on public.products for delete
to authenticated
using (public.is_admin() or seller_id = auth.uid());

-- Seller applications
drop policy if exists "seller_applications_insert_own" on public.seller_applications;
create policy "seller_applications_insert_own"
on public.seller_applications for insert
to authenticated
with check (user_id = auth.uid());

drop policy if exists "seller_applications_select_own_or_admin" on public.seller_applications;
create policy "seller_applications_select_own_or_admin"
on public.seller_applications for select
to authenticated
using (user_id = auth.uid() or public.is_admin());

drop policy if exists "seller_applications_update_admin" on public.seller_applications;
create policy "seller_applications_update_admin"
on public.seller_applications for update
to authenticated
using (public.is_admin())
with check (public.is_admin());

