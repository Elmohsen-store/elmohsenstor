-- منع المستخدم من ترقية حسابه بنفسه إلى بائع/مدير عبر تحديث profiles مباشرة.
create or replace function public.prevent_self_role_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() = old.id
     and not public.is_admin()
     and new.account_type is distinct from old.account_type then
    raise exception 'لا يمكن تغيير نوع الحساب بنفسك؛ يجب موافقة المدير';
  end if;
  return new;
end;
$$;

drop trigger if exists protect_profile_role on public.profiles;
create trigger protect_profile_role
before update on public.profiles
for each row execute procedure public.prevent_self_role_change();

