-- =========================
-- 3) Seller applications
-- =========================
create table if not exists public.seller_applications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  full_name text not null,
  email text not null,
  phone text not null,
  store_name text,
  address text,
  status text not null default 'pending'
    check (status in ('pending','approved','rejected')),
  admin_note text,
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

-- =========================
-- 4) Helper: current profile
-- =========================
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and account_type = 'admin'
  );
$$;

create or replace function public.is_seller()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and account_type = 'seller'
  );
$$;

-- =========================
-- 5) Create profile automatically
-- =========================
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  wanted_type text;
begin
  wanted_type := coalesce(new.raw_user_meta_data->>'account_type', 'buyer');

  if wanted_type not in ('buyer','seller') then
    wanted_type := 'buyer';
  end if;

  insert into public.profiles (
    id, full_name, phone, account_type, store_name, address
  )
  values (
    new.id,
    nullif(new.raw_user_meta_data->>'full_name',''),
    nullif(new.raw_user_meta_data->>'phone',''),
    wanted_type,
    nullif(new.raw_user_meta_data->>'store_name',''),
    nullif(new.raw_user_meta_data->>'address','')
  )
  on conflict (id) do update set
    full_name = excluded.full_name,
    phone = excluded.phone,
    store_name = excluded.store_name,
    address = excluded.address;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;

create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

